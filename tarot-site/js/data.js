function buildDeck(){
  const deck = [];
  MAJOR_ARCANA.forEach(row=>{
    const [num,name,en,element,astro,up,rev] = row;
    deck.push({
      id: "major-"+num,
      arcana: "major",
      number: num,
      name_cn: name,
      name_en: en,
      element,
      astro,
      upright: up,
      reversed: rev
    });
  });
  Object.keys(SUITS).forEach(suitKey=>{
    const suit = SUITS[suitKey];
    for(let i=0;i<14;i++){
      const [up,rev] = MINOR_MEANINGS[suitKey][i];
      deck.push({
        id: suitKey+"-"+(i+1),
        arcana: "minor",
        suit: suitKey,
        suitName: suit.name,
        number: RANKS[i],
        name_cn: suit.name + RANKS[i],
        name_en: RANK_EN[i] + " of " + suit.en,
        element: suit.element,
        astro: suit.theme,
        upright: up,
        reversed: rev
      });
    }
  });
  return deck;
}

const CARDS = buildDeck();

